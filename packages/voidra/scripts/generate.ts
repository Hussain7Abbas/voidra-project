import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { z } from "zod";
import { lifecycles } from "../src/lifecycle.ts";
import { plainSchemas, schemas } from "../src/schemas.ts";
import { templateSchema } from "../src/templates.ts";
import { PACKAGE_VERSION } from "../src/versions.ts";

const roots = ["docs/format/reference", "skills/shared/references"];
export function generatedFiles(): Map<string, string> {
  const files = new Map<string, string>();
  const entries = Object.entries({
    ...schemas,
    ...plainSchemas,
    template: templateSchema,
  });
  const intro =
    "# Generated format reference\n\n[Format index](../Intro.md) · [Documentation index](../../intro.md)\n\nGenerated by `pnpm gen`; schemas describe frontmatter/JSON. The source spec also defines body and cross-file rules.\n\n";
  files.set(
    "docs/format/reference/Intro.md",
    intro +
      entries
        .map(
          ([kind]) =>
            `- [${kind}](${kind}.md) · [JSON Schema](${kind}.schema.json)`,
        )
        .join("\n") +
      "\n",
  );
  const shared: string[] = [
    "# Voidra format 1 reference",
    `Generated by \`pnpm gen\`. Package: voidra ${PACKAGE_VERSION}. Unknown object fields must survive edits. Run \`voidra check\` after writing records. Checks never repair files.`,
    "## Lifecycle defaults",
    `\`\`\`json\n${JSON.stringify(lifecycles, null, 2)}\n\`\`\``,
    "Every lifecycle has a human review gate. Feature, Bug, Improvement and Profile change require exact-byte plan approval. Questions stop any stage. Research writes findings; Release review acceptance authorizes agent finalization and requires commit/tag evidence before Released.",
    "## Writes and approvals",
    "Use `voidra plan <action> --project <folder> --json` to get the current revision. Approval: `voidra approve <action> --by <actor> --revision <revision> --project <folder>`. Never recompute approval from unseen content. Hashes cover requirements.md, blueprint.md and acceptance.md only, never action.md.",
    "For structured Release, the proposal revision also binds members, version/tag, notes, declared files and commit message. Review acceptance authorizes the next agent run; it does not commit, tag or mark work Released. Sync records require reader 0.2.0 and preserve confirmed answers as proposed Profile changes instead of overwriting them.",
    "Use `voidra apply <manifest.json> --project <folder> --json`. A manifest has optional op-prefixed id and changes with path, expectedHash (SHA-256 or null for absent), content (UTF-8 or null for delete). Writes are limited to .voidra/; --glossary explicitly allows root GLOSSARY.md. Paths cannot traverse symlinks or edit recovery metadata. Retain the operation ID for retries. Prepared journals need explicit `voidra recover <op-id> --project <folder>`; use --rollback to undo a partial operation and --glossary for glossary operations. A reused ID with different content fails. An outside edit stops recovery. Checkpoints belong to API tests, never skill manifests.",
    "## Records",
  ];
  for (const [kind, schema] of entries) {
    const json = z.toJSONSchema(schema, {
      target: "draft-2020-12",
      io: "input",
    });
    const raw = `${JSON.stringify(json, null, 2)}\n`;
    files.set(`docs/format/reference/${kind}.schema.json`, raw);
    const properties =
      "properties" in json ? Object.keys(json.properties ?? {}) : [];
    files.set(
      `docs/format/reference/${kind}.md`,
      `# ${kind}\n\n[Reference index](Intro.md) · [Source specification](../${kind}.md) · [JSON Schema](${kind}.schema.json)\n\nGenerated by \`pnpm gen\`; do not edit by hand.\n\n${properties.length ? `Fields: ${properties.map((field) => `\`${field}\``).join(", ")}. Unknown fields are retained.` : "This is a plain UTF-8 text file without frontmatter."} Body and cross-file constraints come from the source specification and the package validator.\n`,
    );
    shared.push(`### ${kind}`, `\`\`\`json\n${raw.trimEnd()}\n\`\`\``);
  }
  files.set("skills/shared/references/format.md", `${shared.join("\n\n")}\n`);
  return files;
}
async function existing(root: string, path: string): Promise<string[]> {
  try {
    const entries = await readdir(join(root, path), { withFileTypes: true });
    const files: string[] = [];
    for (const entry of entries) {
      const file = `${path}/${entry.name}`;
      if (entry.isDirectory()) files.push(...(await existing(root, file)));
      else files.push(file);
    }
    return files;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  }
}
export async function verifyGenerated(root: string): Promise<string[]> {
  const outputs = generatedFiles();
  const stale: string[] = [];
  for (const [path, raw] of outputs) {
    try {
      if ((await readFile(join(root, path), "utf8")) !== raw) stale.push(path);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      stale.push(path);
    }
  }
  for (const folder of roots)
    for (const file of await existing(root, folder))
      if (!outputs.has(file)) stale.push(file);
  return stale.sort();
}
export async function writeGenerated(root: string): Promise<void> {
  for (const [path, raw] of generatedFiles()) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), raw);
  }
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const root = fileURLToPath(new URL("../../../", import.meta.url));
  if (process.argv.includes("--check")) {
    const stale = await verifyGenerated(root);
    if (stale.length) {
      process.stderr.write(
        `Generated references are stale:\n${stale.join("\n")}\nRun pnpm gen.\n`,
      );
      process.exitCode = 1;
    } else process.stdout.write("Generated references are current.\n");
  } else {
    await writeGenerated(root);
    process.stdout.write("Generated format and shared skill references.\n");
  }
}
